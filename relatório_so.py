def _sql(ql):
    gql = '{ r: shopifyqlQuery(query: "%s") { tableData { columns { name } rows } parseErrors } }' % ql
    r = shopify_gql(gql)["r"]
    if r["parseErrors"]:
        raise Exception(f"ShopifyQL: {r['parseErrors']}")
    cols = [c["name"] for c in r["tableData"]["columns"]]
    return pd.DataFrame(r["tableData"]["rows"], columns=cols)

def conv_site_janela(ini, fim):
    a, b = f"{ini:%Y-%m-%d}", f"{fim:%Y-%m-%d}"
    ped = pd.to_numeric(_sql(f"FROM sales SHOW orders SINCE {a} UNTIL {b}")["orders"], errors="coerce").sum()
    ses = pd.to_numeric(_sql(f"FROM sessions SHOW sessions SINCE {a} UNTIL {b}")["sessions"], errors="coerce").sum()
    return sdiv(ped, ses)

