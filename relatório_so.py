def gsheet_url(sheet_id, gid):
    return f"https://docs.google.com/spreadsheets/d/{sheet_id}/export?format=csv&gid={gid}"

def shopify_headers():
    return {
        "X-Shopify-Access-Token": ACCESS_TOKEN,
        "Content-Type": "application/json"
    }

def shopify_gql(query_str):
    """Executa uma query GraphQL no Shopify Admin API."""
    url = f"https://{SHOP_URL}/admin/api/{API_VERSION}/graphql.json"
    resp = requests.post(url, json={"query": query_str}, headers=shopify_headers())
    resp.raise_for_status()
    data = resp.json()
    if "errors" in data:
        raise Exception(f"GraphQL errors: {data['errors']}")
    return data["data"]

def shopify_rest(endpoint, params=None):
    """GET paginado na REST Admin API do Shopify."""
    url = f"https://{SHOP_URL}/admin/api/{API_VERSION}/{endpoint}.json"
    all_items = []
    while url:
        resp = requests.get(url, headers=shopify_headers(), params=params)
        resp.raise_for_status()
        key = list(resp.json().keys())[0]
        all_items.extend(resp.json()[key])
        # Pagination via Link header
        link = resp.headers.get("Link", "")
        url = None
        params = None  # params só no primeiro request
        if 'rel="next"' in link:
            for part in link.split(","):
                if 'rel="next"' in part:
                    url = part.split("<")[1].split(">")[0]
    return all_items

