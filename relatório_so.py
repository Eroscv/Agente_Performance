def brl(v):  return f"R$ {v:,.2f}".replace(",", "X").replace(".", ",").replace("X", ".")
def brl0(v): return f"R$ {v:,.0f}".replace(",", "X").replace(".", ",").replace("X", ".")
def dec(v):  return f"{v:,.2f}".replace(",", "X").replace(".", ",").replace("X", ".")
def pct(v):  return f"{v:.2%}".replace(".", ",")

METRICAS = [
    ("ROAS pago",                 "roas",      dec),
    ("Investimento/dia",          "invest",    brl0),
    ("Receita",                   "receita",   brl0),
    ("CPM",                       "cpm",       brl),
    ("CPC",                       "cpc",       brl),
    ("CTR",                       "ctr",       pct),
    ("Taxa de conversão do site", "conv_site", pct),
    ("Ticket médio",              "ticket",    brl),
]

def dentro(v, r):
    lo, hi = r.get("min"), r.get("max")
    return (lo is None or v >= lo) and (hi is None or v <= hi)

def txt_regua(r, f, key, origem):
    if not tem_regua(r): return "<span style='color:#b0b0b0'>—</span>"
    lo, hi = r.get("min"), r.get("max")
    if lo is not None and hi is not None: t = f"{f(lo)} a {f(hi)}"
    elif lo is not None:                  t = f"≥ {f(lo)}"
    else:                                 t = f"≤ {f(hi)}"
    if key in DIARIAS: t += " /dia"
    if origem == "auto":
        t += " <span style='font-size:9px;color:#aaa'>auto</span>"
    return t

def farol(oks):
    oks = [o for o in oks if o is not None]
    if not oks: return "—", None
    fora = sum(1 for o in oks if not o)
    if fora == 0:            return "🟢", "verde"
    if fora == len(JANELAS): return "🔴", "vermelho"
    return "🟡", "amarelo"

