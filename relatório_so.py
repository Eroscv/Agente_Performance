    body, farol_conta = "", None
    for label, key, f in METRICAS:
        r = regua.get(key, {}) or {}
        principal = key == METRICA_PRINCIPAL
        lbl = f"★ {label}" if principal else label
        row = (f"<td style='{TD};background:#f9f8f5;font-weight:600'>{lbl}</td>"
               f"<td style='{TD};color:#555'>{txt_regua(r, f, key, origem[key])}</td>")
        oks = []
        for n in JANELAS:
            d = dados[n]
            v = d[key]
