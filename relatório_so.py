def shopify_month(s_ini, s_fim):
    result = {}

    # --- total_sales, orders, novos clientes ---
    q1 = (
        f"FROM sales "
        f"SHOW total_sales, orders, customers "
        f"SINCE {s_ini} UNTIL {s_fim} "
        f"GROUP BY new_or_returning_customer"
    )
    gql1 = '{ r: shopifyqlQuery(query: "%s") { tableData { columns { name } rows } parseErrors } }' % q1
    data1 = shopify_gql(gql1)["r"]
    if data1["parseErrors"]:
        raise Exception(f"ShopifyQL error: {data1['parseErrors']}")
    cols1 = [c["name"] for c in data1["tableData"]["columns"]]
    df1 = pd.DataFrame(data1["tableData"]["rows"], columns=cols1)
    for c in ["total_sales", "orders", "customers"]:
        df1[c] = pd.to_numeric(df1[c], errors="coerce").fillna(0)
    result["receita_shopify"] = df1["total_sales"].sum()
    result["n_pedidos"] = df1["orders"].sum()
    result["novos_clientes"] = df1.loc[df1["new_or_returning_customer"] == "New", "customers"].sum()

    # --- gross_sales, discounts ---
    q2 = (
        f"FROM sales "
        f"SHOW gross_sales, discounts "
        f"SINCE {s_ini} UNTIL {s_fim} "
    )
    gql2 = '{ r: shopifyqlQuery(query: "%s") { tableData { columns { name } rows } parseErrors } }' % q2
    data2 = shopify_gql(gql2)["r"]
    if data2["parseErrors"]:
        raise Exception(f"ShopifyQL error: {data2['parseErrors']}")
    cols2 = [c["name"] for c in data2["tableData"]["columns"]]
    df2 = pd.DataFrame(data2["tableData"]["rows"], columns=cols2)
    for c in ["gross_sales", "discounts"]:
        df2[c] = pd.to_numeric(df2[c], errors="coerce").fillna(0)
    result["gross_sales"] = df2["gross_sales"].sum()
    result["discounts"] = abs(df2["discounts"].sum())
    result["taxa_descontos"] = result["discounts"] / result["gross_sales"] if result["gross_sales"] > 0 else 0

    # --- sessões ---
    q3 = (
        f"FROM sessions "
        f"SHOW sessions "
        f"SINCE {s_ini} UNTIL {s_fim} "
    )
    gql3 = '{ r: shopifyqlQuery(query: "%s") { tableData { columns { name } rows } parseErrors } }' % q3
    data3 = shopify_gql(gql3)["r"]
    if data3["parseErrors"]:
        raise Exception(f"ShopifyQL sessions error: {data3['parseErrors']}")
    cols3 = [c["name"] for c in data3["tableData"]["columns"]]
    df3 = pd.DataFrame(data3["tableData"]["rows"], columns=cols3)
    df3["sessions"] = pd.to_numeric(df3["sessions"], errors="coerce").fillna(0)
    result["sessoes"] = df3["sessions"].sum()

    return result

